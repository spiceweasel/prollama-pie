"""Root-side, argument-free nginx configuration writer.

Only consumes an integer port manifest. TLS paths and nginx commands come
from a ROOT-OWNED configuration file, not the daemon-writable manifest.
Install this module in a root-owned venv and grant the daemon only this one
command through sudoers.
"""
import json
import os
import re
import socket
import subprocess
import sys
import tempfile
from pathlib import Path

from .common import port, read_json

PROXY_SETTINGS = "/etc/prollama-pie/proxy-settings.json"

def render(settings, manifest):
    adm = port(settings["admin_public_port"])
    admin_backend = port(settings["admin_backend_port"])
    cert, key = Path(settings["cert"]), Path(settings["key"])
    for file in (cert, key):
        if not file.is_file(): raise ValueError(f"TLS file missing: {file}")
    # Paths and hostname here can be set ONLY by root in proxy-settings.json.
    for value in (str(cert), str(key), settings["server_name"]):
        if not re.fullmatch(r"[a-zA-Z0-9./_:@-]+", value):
            raise ValueError("unsafe TLS path/hostname")
    listen = settings.get("listen_address", "0.0.0.0")
    if listen not in ("0.0.0.0", "127.0.0.1"):
        raise ValueError("listen_address must be 0.0.0.0 or 127.0.0.1")
    routes = manifest.get("routes", [])
    if not isinstance(routes, list) or len(routes) > 2000:
        raise ValueError("invalid route count")
    targets = set()
    backends = set()
    for r in routes:
        p, b = port(r["public_port"]), port(r["backend_port"])
        if p == adm or p == admin_backend or p == b or p in targets or b in backends or b == admin_backend:
            raise ValueError("duplicate or conflicting port")
        targets.add(p); backends.add(b)
    if adm in backends:
        raise ValueError("admin public port conflicts with backend")
    if targets & backends:
        raise ValueError("public ports may not be backend ports")
    def block(public, backend, admin=False):
        # max timeouts support hours-long SSE. No proxy buffering or compression.
        return f'''server {{
    listen {listen}:{public} ssl;
    server_name {settings['server_name']};
    ssl_certificate {cert};
    ssl_certificate_key {key};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:prollama_ssl:10m;
    ssl_session_timeout 1d;
    ssl_session_tickets off;
    ssl_buffer_size 4k;
    client_max_body_size 32m;
    server_tokens off;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy no-referrer always;
    {'' if admin else 'location ~ ^/(metrics|slots|props|health|v1/health)$ { return 403; }'}
    location / {{
        proxy_pass http://127.0.0.1:{backend};
        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $prollama_connection_upgrade;
        proxy_connect_timeout 15s;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        proxy_buffering off;
        proxy_request_buffering off;
        proxy_cache off;
        gzip off;
        add_header Cache-Control no-store always;
        add_header X-Accel-Buffering no always;
    }}
}}
'''
    header = '''# Generated by prollama-pie; DO NOT EDIT.
# This is an http-context include (/etc/nginx/conf.d), NOT a full nginx.conf.
# Reload nginx gracefully: existing connections remain with old workers.
map $http_upgrade $prollama_connection_upgrade {
    default upgrade;
    '' close;
}
'''
    return header + block(adm, admin_backend, True) + "\n".join(block(p, next(r["backend_port"] for r in routes if r["public_port"] == p)) for p in sorted(targets))

def owned_root(path):
    p = Path(path)
    st = p.stat()
    if st.st_uid != 0 or st.st_mode & 0o022:
        raise ValueError(f"root-owned, non-group-writable settings required: {p}")

def apply(settings_file=PROXY_SETTINGS):
    owned_root(settings_file)
    settings = read_json(settings_file)
    manifest = read_json(settings["manifest"], {"routes": []})
    conf_file = Path(settings["output"])
    owned_root(conf_file.parent)
    if not str(conf_file).startswith("/etc/nginx/conf.d/") or conf_file.suffix != ".conf":
        raise ValueError("generated nginx config must be in /etc/nginx/conf.d/*.conf")
    data = render(settings, manifest)
    before = conf_file.read_bytes() if conf_file.exists() else None
    if before == data.encode():
        return "no change"
    # Validate that newly introduced listen ports are not owned by other
    # processes. Existing pro-llama nginx ports already belong to nginx.
    previous_ports = set(map(int, re.findall(r"^\s*listen\s+[\d.]+:(\d+)\s+ssl;", (before or b"").decode(), flags=re.M)))
    requested_ports = set(map(int, re.findall(r"^\s*listen\s+[\d.]+:(\d+)\s+ssl;", data, flags=re.M)))
    for p in requested_ports - previous_ports:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            try: sock.bind((settings.get("listen_address", "0.0.0.0"), p))
            except OSError as e: raise ValueError(f"public port {p} already in use: {e}") from e
    conf_file.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".pro-llama-", dir=conf_file.parent)
    try:
        os.fchmod(fd, 0o644)
        with os.fdopen(fd, "w") as f:
            f.write(data)
            f.flush(); os.fsync(f.fileno())
        os.replace(tmp, conf_file)
        test = subprocess.run([settings.get("nginx_binary", "/usr/sbin/nginx"), "-t"], capture_output=True, text=True, timeout=15)
        if test.returncode:
            raise RuntimeError("nginx -t failed: " + test.stderr.strip())
        run = subprocess.run(settings.get("reload_command", ["/usr/bin/systemctl", "reload", "nginx"]), capture_output=True, text=True, timeout=15)
        if run.returncode:
            raise RuntimeError("nginx graceful reload failed: " + run.stderr.strip())
        return "nginx configuration applied; graceful reload sent"
    except Exception:
        # Roll back the actual nginx file. The earlier config remains active
        # when nginx -t fails or reload returns nonzero.
        if before is None: conf_file.unlink(missing_ok=True)
        else:
            fd, rollback = tempfile.mkstemp(prefix=".pro-llama-revert-", dir=conf_file.parent)
            try:
                with os.fdopen(fd, "wb") as f: f.write(before)
                os.chmod(rollback, 0o644)
                os.replace(rollback, conf_file)
            finally:
                if os.path.exists(rollback): os.unlink(rollback)
        raise
    finally:
        if os.path.exists(tmp): os.unlink(tmp)

def main():
    if os.geteuid() != 0:
        sys.exit("must run as root (via tightly scoped sudoers helper)")
    if len(sys.argv) != 1:
        sys.exit("usage: pro-llama-nginx-apply (no arguments)")
    try: print(apply())
    except Exception as e: sys.exit(f"nginx apply: {e}")

if __name__ == "__main__": main()
